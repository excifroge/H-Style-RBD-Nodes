# interface text that reads the same in every language
SAME = ("RBD", "H-Style RBD Nodes", "Unity", "X", "Y", "Z")


CONTEXT = "H-Style RBD Nodes"   # for labels whose plain word Blender itself translates differently


def _table():
    table = {}
    for src, dst in ZH.items():
        for ctx in ("*", "Operator", CONTEXT):
            table[(ctx, src)] = dst
    return {"zh_HANS": table, "zh_CN": table}


def register():
    try:
        bpy.app.translations.register(__package__, _table())
    except ValueError:
        bpy.app.translations.unregister(__package__)
        bpy.app.translations.register(__package__, _table())


def unregister():
    bpy.app.translations.unregister(__package__)
